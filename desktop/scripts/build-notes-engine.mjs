// Bundles the OLIVE Notes replica engine for the iOS app's JavaScriptCore.
// Output: mobile/ios/OLIVEMobile/Resources/NotesEngine.js (committed, because
// Xcode builds do not run npm). The header records a hash of every input so
// a test can prove the committed bundle matches its sources.
import { build } from "vite";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const desktop = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(desktop, "..");
const engine = join(desktop, "src/features/notes/engine");
export const inputs = ["phone-entry.ts", "replica.ts", "protocol.ts", "doc.ts", "text.ts", "protocol_v1.json"].map((f) => join(engine, f))
  .concat([join(desktop, "node_modules/yjs/package.json"), join(desktop, "node_modules/lib0/package.json")]);

export function inputHash() {
  const hash = createHash("sha256");
  for (const file of inputs) hash.update(relative(root, file).replaceAll("\\", "/")).update("\0").update(readFileSync(file)).update("\0");
  return hash.digest("hex");
}

// Runs before the bundle's modules: JavaScriptCore has no WebCrypto or console.
const prelude = `(function (g) {
  if (!g.console) g.console = { log: function () {}, warn: function () {}, error: function () {} };
  if (!g.crypto || !g.crypto.getRandomValues) {
    var A = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    g.crypto = { getRandomValues: function (array) {
      var text = g.OliveNotesHost.randomBytes(array.byteLength), bytes = new Uint8Array(array.buffer, array.byteOffset, array.byteLength), o = 0;
      for (var i = 0; i < text.length; i += 4) {
        var n = (A.indexOf(text[i]) << 18) | (A.indexOf(text[i + 1]) << 12) | ((A.indexOf(text[i + 2]) & 63) << 6) | (A.indexOf(text[i + 3]) & 63);
        if (o < bytes.length) bytes[o++] = (n >> 16) & 255;
        if (o < bytes.length) bytes[o++] = (n >> 8) & 255;
        if (o < bytes.length) bytes[o++] = n & 255;
      }
      return array;
    } };
  }
})(globalThis);`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = mkdtempSync(join(tmpdir(), "olive-notes-engine-"));
  try {
    await build({
      configFile: false,
      logLevel: "warn",
      build: {
        outDir: out,
        emptyOutDir: true,
        minify: true,
        target: "es2020",
        lib: { entry: join(engine, "phone-entry.ts"), formats: ["iife"], name: "OliveNotesBundle", fileName: () => "engine.js" },
        rollupOptions: { output: { banner: prelude } },
      },
    });
    const code = readFileSync(join(out, "engine.js"), "utf8");
    const header = `/* OLIVE Notes phone engine. GENERATED by desktop/scripts/build-notes-engine.mjs; do not edit.\n` +
      ` * inputs-sha256: ${inputHash()}\n * Includes yjs ${JSON.parse(readFileSync(inputs[6])).version} and lib0 ${JSON.parse(readFileSync(inputs[7])).version} (MIT, Kevin Jahns); see NotesEngine.LICENSES.txt. */\n`;
    writeFileSync(join(root, "mobile/ios/OLIVEMobile/Resources/NotesEngine.js"), header + code);
    console.log(`NotesEngine.js written (${(header.length + code.length).toLocaleString()} bytes)`);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}
